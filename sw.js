const CACHE_NAME = 'basai-shell-v2'; // versi dinaikkan supaya cache lama otomatis dibuang
const APP_SHELL = ['./index.html', './manifest.json', './icon-192.png', './icon-512.png'];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(APP_SHELL))
      .catch((err) => console.warn('SW: gagal precache app shell', err))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

// Strategi: NETWORK-FIRST untuk semua aset milik sendiri (index.html, manifest,
// ikon) supaya update terbaru selalu langsung terlihat selama online. Cache
// hanya dipakai sebagai fallback kalau benar-benar offline. Request ke
// Cloudflare Worker/Groq/CDN eksternal sama sekali tidak disentuh (biar
// streaming SSE tidak rusak).
self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  if (!req.url.startsWith(self.location.origin)) return;

  event.respondWith(
    fetch(req)
      .then((res) => {
        if (res && res.ok) {
          const clone = res.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(req, clone));
        }
        return res;
      })
      .catch(() => caches.match(req))
  );
});
